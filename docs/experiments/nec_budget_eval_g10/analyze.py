"""Analysis for docs/experiments/nec_budget_eval_g10/PROTOCOL.md. Written before the runs; frozen with the protocol.

usage: python docs/experiments/nec_budget_eval_g10/analyze.py [results_root] [out_dir]
Reads <root>/**/*_s<seed>.json, writes results.md, per_run.csv, learning_curves.png and steering_by_distance.png to out_dir.

O1 (primary outcome) = per run, the mean evaluation score (20 episodes at epsilon 0.05) over its last three evaluations (230k, 240k, 250k).
H1/H2/H3 are exactly as in PROTOCOL.md section 1; everything else is labelled exploratory.
"""
import csv, glob, json, os, sys
import numpy as np

ROOT = sys.argv[1] if len(sys.argv) > 1 else "results/exp_nec_budget_eval_g10"
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.dirname(os.path.abspath(__file__))
B, BOOT_SEED = 10000, 12345
NEC_ARMS = {7.92e-6: "NEC 7.92e-6", 3e-5: "NEC 3e-5", 1e-4: "NEC 1e-4"}
PRIMARY = "NEC 1e-4"  # pre-declared arm for H2 and H3
ORDER = ["random", "DQN", "frozen", *NEC_ARMS.values()]
H1_MIN, H3_MIN = 0.25, 0.50


def condition(d):
    a = d["agent"]
    if a == "random": return "random"
    if a == "dqn_naturecnn": return "DQN"
    if a == "ec_frozen_naturecnn": return "frozen"
    if a == "nec_naturecnn":
        for lr, name in NEC_ARMS.items():
            if d.get("lr") is not None and abs(d["lr"] - lr) < 1e-12 * max(1, abs(lr)) + 1e-15: return name
    return None


def run_metrics(d):
    ev = d.get("evaluations") or []
    last = ev[-3:]
    m = dict(seed=d["seed"], steps=d["steps"], wall_h=d["wallclock_s"] / 3600)
    m["o1"] = float(np.mean([np.mean([e[0] for e in eps]) for _, eps in last])) if last else np.nan
    m["eval_len"] = float(np.mean([np.mean([e[3] for e in eps]) for _, eps in last])) if last else np.nan
    T = d["steps"]
    sc = [x[1] for x in d["episodes"] if x[0] > T / 2]
    m["train_fruit"] = float(np.mean(sc)) if sc else np.nan
    pr = {t: p for t, p in d.get("probes", [])}
    for tag, t in (("final", d["steps"]), ("t60k", 60000)):
        p = pr.get(t, {})
        m[f"steer_{tag}"], m[f"chance_{tag}"] = p.get("steer"), p.get("steer_chance")
        m[f"decode_{tag}"] = p.get("decode")
        far = p.get("far") or {}
        m[f"alltied_{tag}"], m[f"toptied_{tag}"] = far.get("all_tied"), far.get("top_tied")
        m[f"far_steer_{tag}"] = far.get("steer_by_dist")
        m[f"far_chance_{tag}"] = far.get("chance_by_dist")
    kn = [s["key_norm"] for _, s in d.get("train", []) if "key_norm" in s]
    m["key_norm_max"] = max(kn) if kn else None
    last_diag = d["diagnostics"][-1][1] if d.get("diagnostics") else None
    if last_diag:
        a = np.array([last_diag[k]["appends"] for k in sorted(last_diag)], float)
        m["max_append_share"] = float(a.max() / a.sum()) if a.sum() else None
    m["curve"] = [(t, float(np.mean([e[0] for e in eps]))) for t, eps in ev]
    return m


def boot_diff(a, b, level, rng):
    a, b = np.asarray(a, float), np.asarray(b, float)
    da = a[rng.integers(len(a), size=(B, len(a)))].mean(1)
    db = b[rng.integers(len(b), size=(B, len(b)))].mean(1)
    lo, hi = (100 - level) / 2, 100 - (100 - level) / 2
    return float(a.mean() - b.mean()), tuple(np.percentile(da - db, [lo, hi]))


def fmt(x, k=2):
    return "-" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{k}f}"


def main():
    runs = {}
    for f in sorted(glob.glob(f"{ROOT}/**/*_s[0-9]*.json", recursive=True)):
        d = json.load(open(f))
        c = condition(d)
        if c is None:
            print("skipping", f); continue
        runs.setdefault(c, []).append(run_metrics(d))
    if not runs:
        sys.exit(f"no results under {ROOT}")
    for c in runs: runs[c].sort(key=lambda m: m["seed"])
    rng = np.random.default_rng(BOOT_SEED)
    o1 = {c: [m["o1"] for m in runs[c]] for c in runs}
    L = ["# Results: NEC budget and evaluation (generated by analyze.py)", "",
         f"Runs per condition: " + ", ".join(f"{c} {len(runs[c])}" for c in ORDER if c in runs), ""]

    L += ["## Primary outcome O1 (evaluation score, last three evaluations; epsilon 0.05, 20 episodes each)", "",
          "| Condition | n | mean | s.d. | per-seed | eval episode length | train fruit (2nd half) |", "|---|---|---|---|---|---|---|"]
    for c in ORDER:
        if c in runs:
            v = o1[c]
            L.append(f"| {c} | {len(v)} | {np.mean(v):.2f} | {np.std(v, ddof=1) if len(v) > 1 else float('nan'):.2f} | "
                     f"{', '.join(f'{x:.2f}' for x in v)} | {np.mean([m['eval_len'] for m in runs[c]]):.0f} | "
                     f"{np.mean([m['train_fruit'] for m in runs[c]]):.2f} |")

    L += ["", "## Confirmatory hypotheses", ""]
    if "frozen" in runs:
        L += ["**H1** (NEC arm minus frozen EC; supported if difference >= +0.25 and the 98.3% interval excludes 0):", ""]
        for arm in NEC_ARMS.values():
            if arm in runs:
                d, (lo, hi) = boot_diff(o1[arm], o1["frozen"], 100 * (1 - 0.05 / 3), rng)
                ok = d >= H1_MIN and lo > 0
                L.append(f"- {arm}: {d:+.2f} [{lo:+.2f}, {hi:+.2f}] -> **{'supported' if ok else 'not supported'}**")
    if PRIMARY in runs and "DQN" in runs:
        d, (lo, hi) = boot_diff(o1[PRIMARY], o1["DQN"], 95, rng)
        L += ["", f"**H2** ({PRIMARY} minus DQN; supported if the 95% interval lies above 0): {d:+.2f} [{lo:+.2f}, {hi:+.2f}] -> "
              f"**{'supported' if lo > 0 else 'not supported'}**"]
    if PRIMARY in runs:
        st = [m["steer_final"] for m in runs[PRIMARY] if m["steer_final"] is not None]
        if st:
            mean = float(np.mean(st))
            L += ["", f"**H3** ({PRIMARY} near-probe steering at the end, supported if the mean over seeds >= {H3_MIN}): mean {mean:.2f} "
                  f"(per seed {', '.join(f'{x:.2f}' for x in st)}; chance {np.mean([m['chance_final'] for m in runs[PRIMARY]]):.2f}) -> "
                  f"**{'supported' if mean >= H3_MIN else 'not supported'}**"]

    L += ["", "## Exploratory (not pre-registered tests)", "", "### Each learned agent against the random baseline (O1 difference, 95% bootstrap interval)", ""]
    if "random" in runs:
        for c in ORDER[1:]:
            if c in runs:
                d, (lo, hi) = boot_diff(o1[c], o1["random"], 95, rng)
                L.append(f"- {c}: {d:+.2f} [{lo:+.2f}, {hi:+.2f}]")
    learned = [c for c in NEC_ARMS.values() if c in runs]
    if learned and "DQN" in runs:
        best = max(learned, key=lambda c: np.mean(o1[c]))
        d, (lo, hi) = boot_diff(o1[best], o1["DQN"], 95, rng)
        L += ["", f"### Best-of-three NEC arm against DQN (**selected after the fact, favours NEC**): {best}: {d:+.2f} [{lo:+.2f}, {hi:+.2f}]"]

    L += ["", "### Probe: near steering, ties and distance (end of training and at 60k; mean over seeds)", "",
          "| Condition | steer end | chance | steer 60k | decode end | all tied end | top tied end | all tied 60k | max action append share |", "|---|---|---|---|---|---|---|---|---|"]
    def mean_of(c, k):
        v = [m[k] for m in runs[c] if m.get(k) is not None]
        return float(np.mean(v)) if v else None
    for c in ORDER:
        if c in runs and c != "random":
            L.append(f"| {c} | {fmt(mean_of(c,'steer_final'))} | {fmt(mean_of(c,'chance_final'))} | {fmt(mean_of(c,'steer_t60k'))} | "
                     f"{fmt(mean_of(c,'decode_final'))} | {fmt(mean_of(c,'alltied_final'))} | {fmt(mean_of(c,'toptied_final'))} | "
                     f"{fmt(mean_of(c,'alltied_t60k'))} | {fmt(mean_of(c,'max_append_share'))} |")
    L += ["", "Reading rule from the protocol: where `all tied` > 0.5, chance-level steering means missing information, not misinformation.", "",
          "### Steering by walkable distance to the food, end of training (mean over seeds; chance in brackets)", "",
          "| Condition | d=1 | d=2 | d=3 | d=4 | d=5 | d=6 |", "|---|---|---|---|---|---|---|"]
    for c in ORDER:
        if c in runs and c != "random":
            arr = [m["far_steer_final"] for m in runs[c] if m.get("far_steer_final")]
            ch = [m["far_chance_final"] for m in runs[c] if m.get("far_chance_final")]
            if arr:
                cells = []
                for i in range(6):
                    v = [a[i] for a in arr if a[i] is not None]
                    w = [a[i] for a in ch if a[i] is not None]
                    cells.append(f"{np.mean(v):.2f} ({np.mean(w):.2f})" if v else "-")
                L.append(f"| {c} | " + " | ".join(cells) + " |")
    L += ["", "### Key norm (max over the run, mean over seeds) and wall-clock hours", "", "| Condition | key norm max | wall h (mean, max) |", "|---|---|---|"]
    for c in ORDER:
        if c in runs:
            L.append(f"| {c} | {fmt(mean_of(c,'key_norm_max'))} | {np.mean([m['wall_h'] for m in runs[c]]):.1f}, {max(m['wall_h'] for m in runs[c]):.1f} |")
    open(f"{OUT}/results.md", "w").write("\n".join(L) + "\n")

    with open(f"{OUT}/per_run.csv", "w", newline="") as f:
        cols = ["condition", "seed", "o1", "eval_len", "train_fruit", "steer_final", "chance_final", "decode_final", "alltied_final", "toptied_final",
                "steer_t60k", "alltied_t60k", "key_norm_max", "max_append_share", "wall_h"]
        w = csv.writer(f); w.writerow(cols)
        for c in ORDER:
            for m in runs.get(c, []): w.writerow([c] + [m.get(k) for k in cols[1:]])

    try:
        import matplotlib; matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception as e:
        print("no matplotlib, skipping figures:", e); print("\n".join(L)); return
    fig, ax = plt.subplots(figsize=(7, 4.2))
    for c in ORDER:
        if c in runs and runs[c][0]["curve"]:
            ts = [t for t, _ in runs[c][0]["curve"]]
            Y = np.array([[y for _, y in m["curve"]] for m in runs[c] if len(m["curve"]) == len(ts)])
            mu, se = Y.mean(0), (Y.std(0, ddof=1) / np.sqrt(len(Y)) if len(Y) > 1 else 0 * Y.mean(0))
            ax.plot(ts, mu, label=c); ax.fill_between(ts, mu - se, mu + se, alpha=0.2)
    ax.set_xlabel("training step"); ax.set_ylabel("evaluation score (fruit per episode)"); ax.grid(alpha=0.3); ax.legend(fontsize=8)
    ax.set_title("Evaluation score (epsilon 0.05), mean ± s.e. over seeds"); fig.tight_layout(); fig.savefig(f"{OUT}/learning_curves.png", dpi=130)
    fig, ax = plt.subplots(figsize=(7, 4.2))
    for c in ORDER:
        if c in runs and c != "random":
            arr = [m["far_steer_final"] for m in runs[c] if m.get("far_steer_final")]
            if arr:
                A = np.array([[np.nan if v is None else v for v in a] for a in arr]); ax.plot(range(1, 7), np.nanmean(A, 0), marker="o", label=c)
    ch = [m["far_chance_final"] for c in runs for m in runs[c] if m.get("far_chance_final")]
    if ch: ax.plot(range(1, 7), np.nanmean(np.array([[np.nan if v is None else v for v in a] for a in ch]), 0), "k--", label="chance")
    ax.set_xlabel("walkable steps from the head to the food"); ax.set_ylabel("steering"); ax.grid(alpha=0.3); ax.legend(fontsize=8)
    fig.tight_layout(); fig.savefig(f"{OUT}/steering_by_distance.png", dpi=130)
    print(f"wrote results.md, per_run.csv and two figures to {OUT}")


if __name__ == "__main__":
    main()
