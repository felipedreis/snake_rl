"""Tables for the pixels + RMSProp exploration (PLAN.md).

usage (from the repo root):
  .venv/bin/python docs/experiments/pixels_rmsprop_probe/analyze.py [--root results/exp_pixels_rmsprop] [--out DIR]
Writes <out>/results.md (default: this directory). Safe to run on partial results: missing runs are skipped.
"""
import argparse
import glob
import json
import os
from collections import defaultdict

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ORDER = ["random", "mfec grid", "mfec pixels", "EC frozen (Nature)", "DQN (Nature) Adam 5e-4", "DQN (Nature) RMSProp 2.5e-4",
         "NEC (Nature) Adam 5e-4", "NEC (Nature) RMSProp 2.5e-4", "NEC (Nature) RMSProp 1e-3"]


def variant(d):
    a, opt, lr = d["agent"], d.get("opt", "adam"), d.get("lr")
    if a == "random":
        return "random"
    if a == "mfec":
        return "mfec pixels" if d.get("render") == "pixels" else "mfec grid"
    if a == "ec_frozen_naturecnn":
        return "EC frozen (Nature)"
    base = {"dqn_naturecnn": "DQN (Nature)", "nec_naturecnn": "NEC (Nature)"}[a]
    return base + (" Adam 5e-4" if opt == "adam" else f" RMSProp {lr:g}".replace("0.00025", "2.5e-4").replace("0.001", "1e-3"))


def setting(d):
    return f"{d['size']}x{d['size']}" + (" rooms+bonus (held phase)" if d.get("map", "open") == "rooms" else " open")


def late(d):
    """Open boards: mean score per episode over the second half. 25x25: regular fruit per 100 training steps after
    the epsilon decay (steps 50k..end), the held-phase signal."""
    e = np.array(d["episodes"])
    T = d["steps"]
    if d.get("map", "open") == "rooms":
        m = e[:, 0] > 50_000
        return float(e[m, 2].sum() * 100.0 / (T - 50_000))
    m = e[:, 0] > T / 2
    return float(e[m, 1].mean()) if m.any() else float("nan")


def tele(d, key, first=False):
    tr = d.get("train") or []
    if not tr:
        return float("nan")
    return float((tr[0] if first else tr[-1])[1].get(key, float("nan")))


def probe_last(d, key):
    pr = d.get("probes") or []
    return float(pr[-1][1].get(key, float("nan"))) if pr and pr[-1][1] else float("nan")


def probe_first(d, key):
    pr = d.get("probes") or []
    return float(pr[0][1].get(key, float("nan"))) if pr and pr[0][1] else float("nan")


def fmt(xs, p=2):
    xs = [x for x in xs if not np.isnan(x)]
    if not xs:
        return "–"
    return f"{np.mean(xs):.{p}f}" + (f" ({', '.join(f'{x:.{p}f}' for x in xs)})" if len(xs) > 1 else "")


def main(root, out):
    runs = defaultdict(list)  # (setting, variant) -> [json]
    for f in sorted(glob.glob(f"{root}/*/*_s[0-9].json")):
        d = json.load(open(f))
        runs[(setting(d), variant(d))].append(d)
    settings = sorted({k[0] for k in runs}, key=lambda s: (int(s.split("x")[0]), s))
    L = ["# Results: pixels + RMSProp exploration", "", f"Generated by analyze.py from `{root}`. Each cell: mean over seeds, "
         "per-seed values in brackets. Exploratory (PLAN.md); n = 1–2 seeds, so read patterns, not differences.", ""]
    for s in settings:
        rows = [(v, runs[(s, v)]) for v in ORDER if (s, v) in runs]
        held = "rooms" in s
        L += [f"## {s}", "",
              "| agent | " + ("held-phase fruit / 100 steps | " if held else "LATE score / episode | ")
              + "key norm start → end | dead ReLU (end) | update/weight (end) | probe steer | probe decode | probe knn_offset | probe food_ratio | wall (min) |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for v, ds in rows:
            kn = [f"{tele(d, 'key_norm', True):.2f} → {tele(d, 'key_norm'):.3g}" for d in ds if not np.isnan(tele(d, 'key_norm'))]
            L.append(f"| {v} | {fmt([late(d) for d in ds])} | {'; '.join(kn) or '–'} | {fmt([tele(d, 'dead_relu') for d in ds])} | "
                     f"{fmt([tele(d, 'update_ratio') for d in ds], 4)} | {fmt([probe_last(d, 'steer') for d in ds], 3)} | "
                     f"{fmt([probe_last(d, 'decode') for d in ds], 3)} | {fmt([probe_last(d, 'knn_offset') for d in ds], 3)} | "
                     f"{fmt([probe_last(d, 'food_ratio') for d in ds], 2)} | {np.mean([d['wallclock_s'] for d in ds]) / 60:.0f} |")
        L.append("")
    L += ["Probe chance levels: `steer` 0.40, `decode` 0.10. `key_norm` is the mean ‖h‖ of the training minibatch (NEC only; "
          "1,000-step window means).", ""]
    open(f"{out}/results.md", "w").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="results/exp_pixels_rmsprop")
    ap.add_argument("--out", default=HERE)
    a = ap.parse_args()
    main(a.root, a.out)
